package code.tenant

import code.api.Constant.DYNAMIC_ENTITY_SYSTEM_LEVEL_BANK_ID
import code.api.util.APIUtil
import code.api.util.migration.{MigrationOfOrganisationToTenant, RoleRows}
import code.entitlement.MappedEntitlement
import code.group.GroupTrait
import code.setup.ServerSetup
import net.liftweb.db.DB
import net.liftweb.util.DefaultConnectionIdentifier
import org.scalatest.Tag

/**
 * The migration from Organisation to Tenant: rows of the old table are copied into Tenant without their bank id, the Organisation Roles held at SYS or the empty bank id become the Tenant system Roles, one held at a bank
 * is left alone, and a Group at SYS holding only those Roles moves to the system level.
 */
class TenantMigrationTest extends ServerSetup {

  object TenantMigration extends Tag("TenantMigration")

  private val suffix = APIUtil.generateUUID().take(8)
  private val userId = s"tenant-migration-user-$suffix"

  private def sql(statement: String, values: Any*): Unit =
    DB.use(DefaultConnectionIdentifier) { connection =>
      val prepared = connection.prepareStatement(statement)
      try {
        values.zipWithIndex.foreach {
          case (v: String, i) => prepared.setString(i + 1, v)
          case (v: Boolean, i) => prepared.setBoolean(i + 1, v)
          case (v, i) => prepared.setObject(i + 1, v)
        }
        prepared.executeUpdate()
      } finally prepared.close()
    }

  /** The old tables, as Organisation and OrganisationMember stored them. */
  private def oldTables(): Unit = {
    sql("CREATE TABLE IF NOT EXISTS organisation (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organisationid VARCHAR(64), " +
      "bankid VARCHAR(255), name VARCHAR(255), website VARCHAR(1024), logourl VARCHAR(1024), organisationtype VARCHAR(64), " +
      "status VARCHAR(32), visibility VARCHAR(32), createdbyuserid VARCHAR(255), creationdate TIMESTAMP, lastupdate TIMESTAMP)")
    // The changelog's organisation table predates the bank id and type columns, so a database that already has
    // the table needs the columns the old rows carried.
    sql("ALTER TABLE organisation ADD COLUMN IF NOT EXISTS bankid VARCHAR(255)")
    sql("ALTER TABLE organisation ADD COLUMN IF NOT EXISTS organisationtype VARCHAR(64)")
    sql("CREATE TABLE IF NOT EXISTS organisationmember (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organisationmemberid VARCHAR(36), " +
      "organisationid VARCHAR(64), userid VARCHAR(255), memberrole VARCHAR(32), title VARCHAR(255), status VARCHAR(32), " +
      "isprimary BOOLEAN, createdbyuserid VARCHAR(255), createdbyonbehalfofuserid VARCHAR(255), updatedbyuserid VARCHAR(255), " +
      "updatedbyonbehalfofuserid VARCHAR(255), creationdate TIMESTAMP, lastupdate TIMESTAMP)")
  }

  private def giveEntitlement(bankId: String, roleName: String): Unit =
    MappedEntitlement.insert(bankId, userId, roleName, createdByProcess = "", grantedByUserId = None, groupId = None)

  private def entitlementsOf(roleName: String): List[String] =
    MappedEntitlement.findAllByUserId(userId).filter(_.roleName == roleName).map(_.bankId)

  feature("Organisation becomes Tenant") {

    scenario("Organisations are copied into the Tenant table, once", TenantMigration) {
      oldTables()
      val orgId = s"old-org-$suffix"
      val now = new java.sql.Timestamp(System.currentTimeMillis())
      sql("INSERT INTO organisation (organisationid, bankid, name, website, logourl, organisationtype, status, visibility, " +
        "createdbyuserid, creationdate, lastupdate) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        orgId, DYNAMIC_ENTITY_SYSTEM_LEVEL_BANK_ID, "Old Org", "https://example.com", "", "startup", "active", "public", userId, now, now)

      MigrationOfOrganisationToTenant.migrate(s"testTenantRows_$suffix") shouldBe true
      val tenant = Tenants.tenant.vend.getTenant(orgId).openOrThrowException("tenant should exist")
      tenant.name shouldBe "Old Org"
      tenant.website shouldBe Some("https://example.com")

      And("running it again copies nothing twice")
      MigrationOfOrganisationToTenant.migrate(s"testTenantRowsAgain_$suffix") shouldBe true
      Tenant.findAll().count(_.tenantId == orgId) shouldBe 1
    }

    scenario("Organisation Roles at SYS or the empty bank id become Tenant system Roles; one at a bank is left", TenantMigration) {
      giveEntitlement(DYNAMIC_ENTITY_SYSTEM_LEVEL_BANK_ID, "CanCreateOrganisation")
      giveEntitlement("", "CanGetAnyOrganisation")
      giveEntitlement("some-bank", "CanUpdateOrganisation")
      giveEntitlement("", "CanUpdateOrganisationMember")
      giveEntitlement("", "CanGetAnyUser")

      MigrationOfOrganisationToTenant.migrate(s"testTenantRoles_$suffix") shouldBe true
      entitlementsOf("CanCreateTenant") shouldBe List("")
      entitlementsOf("CanGetTenant") shouldBe List("")
      entitlementsOf("CanCreateOrganisation") shouldBe Nil
      entitlementsOf("CanUpdateOrganisation") shouldBe List("some-bank")
      entitlementsOf("CanUpdateTenant") shouldBe Nil
      And("a member Role has no successor and is left as it was")
      entitlementsOf("CanUpdateOrganisationMember") shouldBe List("")
      entitlementsOf("CanGetAnyUser") shouldBe List("")
    }

    scenario("A Group at SYS holding only Organisation Roles moves to the system level; a mixed one stays", TenantMigration) {
      def makeGroup(name: String, roles: List[String]): Unit =
        GroupTrait.group.vend.createGroup(Some(DYNAMIC_ENTITY_SYSTEM_LEVEL_BANK_ID), name, "tenant migration test", roles, isEnabled = true)
          .openOrThrowException(s"group $name should be created")
      // Read back as stored: the raw bank id and the comma-joined Roles.
      def reload(name: String): RoleRows.GroupRow =
        RoleRows.groups().find(_.groupName == name).getOrElse(fail(s"group $name"))
      val only = s"tenant-admins-$suffix"
      val mixed = s"mixed-admins-$suffix"
      makeGroup(only, List("CanGetOrganisation", "CanUpdateOrganisation"))
      makeGroup(mixed, List("CanGetOrganisation", "CanCreateDynamicEntityDefinition"))

      MigrationOfOrganisationToTenant.migrate(s"testTenantGroups_$suffix") shouldBe true
      reload(only).bankId shouldBe ""
      reload(only).listOfRoles shouldBe "CanGetTenant,CanUpdateTenant"
      reload(mixed).bankId shouldBe DYNAMIC_ENTITY_SYSTEM_LEVEL_BANK_ID
      reload(mixed).listOfRoles shouldBe "CanGetTenant,CanCreateDynamicEntityDefinition"
    }
  }
}
