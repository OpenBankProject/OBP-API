    "MBRANCHID" CHARACTER VARYING(44),
    "MNAME" CHARACTER VARYING(255),
    "MLINE1" CHARACTER VARYING(255),
    "MLINE2" CHARACTER VARYING(255),
    "MLINE3" CHARACTER VARYING(255),
    "MCITY" CHARACTER VARYING(255),
    "MCOUNTY" CHARACTER VARYING(255),
    "MSTATE" CHARACTER VARYING(255),
    "MPOSTCODE" CHARACTER VARYING(20),
    "MCOUNTRYCODE" CHARACTER VARYING(2),
    "MLOCATIONLATITUDE" DOUBLE PRECISION,
    "MLOCATIONLONGITUDE" DOUBLE PRECISION,
    "MLICENSEID" CHARACTER VARYING(44),
    "MLICENSENAME" CHARACTER VARYING(255),
    "MLOBBYHOURS" CHARACTER VARYING(2000),
    "MDRIVEUPHOURS" CHARACTER VARYING(2000),
    "MISACCESSIBLE" CHARACTER VARYING(1),
    "MBRANCHTYPE" CHARACTER VARYING(32),
    "MMOREINFO" CHARACTER VARYING(128),
    "MPHONENUMBER" CHARACTER VARYING(32),
    "MISDELETED" BOOLEAN,
    "MBANKID" CHARACTER VARYING(44),
    "MBRANCHROUTINGSCHEME" CHARACTER VARYING(32),
    "MBRANCHROUTINGADDRESS" CHARACTER VARYING(64),
    "MLOBBYOPENINGTIMEONMONDAY" CHARACTER VARYING(5),
    "MLOBBYCLOSINGTIMEONMONDAY" CHARACTER VARYING(5),
    "MLOBBYOPENINGTIMEONTUESDAY" CHARACTER VARYING(5),
    "MLOBBYCLOSINGTIMEONTUESDAY" CHARACTER VARYING(5),
    "MLOBBYOPENINGTIMEONWEDNESDAY" CHARACTER VARYING(5),
    "MLOBBYCLOSINGTIMEONWEDNESDAY" CHARACTER VARYING(5),
    "MLOBBYOPENINGTIMEONTHURSDAY" CHARACTER VARYING(5),
    "MLOBBYCLOSINGTIMEONTHURSDAY" CHARACTER VARYING(5),
    "MLOBBYOPENINGTIMEONFRIDAY" CHARACTER VARYING(5),
    "MLOBBYCLOSINGTIMEONFRIDAY" CHARACTER VARYING(5),
    "MLOBBYOPENINGTIMEONSATURDAY" CHARACTER VARYING(5),
    "MLOBBYCLOSINGTIMEONSATURDAY" CHARACTER VARYING(5),
    "MLOBBYOPENINGTIMEONSUNDAY" CHARACTER VARYING(5),
    "MLOBBYCLOSINGTIMEONSUNDAY" CHARACTER VARYING(5),
    "MDRIVEUPOPENINGTIMEONMONDAY" CHARACTER VARYING(5),
    "MDRIVEUPCLOSINGTIMEONMONDAY" CHARACTER VARYING(5),
    "MDRIVEUPOPENINGTIMEONTUESDAY" CHARACTER VARYING(5),
    "MDRIVEUPCLOSINGTIMEONTUESDAY" CHARACTER VARYING(5),
    "MDRIVEUPOPENINGTIMEONWEDNESDAY" CHARACTER VARYING(5),
    "MDRIVEUPCLOSINGTIMEONWEDNESDAY" CHARACTER VARYING(5),
    "MDRIVEUPOPENINGTIMEONTHURSDAY" CHARACTER VARYING(5),
    "MDRIVEUPCLOSINGTIMEONTHURSDAY" CHARACTER VARYING(5),
    "MDRIVEUPOPENINGTIMEONFRIDAY" CHARACTER VARYING(5),
