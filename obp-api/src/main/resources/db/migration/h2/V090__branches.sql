-- Branches: one row per (bank, branch).
--
-- Fifty columns, almost all of them nullable in practice, because the connector writes many of
-- them through orNull — mcounty, mbranchroutingscheme, mbranchroutingaddress, every drive-up
-- opening and closing time, mbranchtype, mmoreinfo and mphonenumber all genuinely hold NULL. The
-- reader surfaces them as null again, which is what Lift's MappedString did; binding them as bare
-- Strings would throw at write time instead.
--
-- The lobby times are the exception: the connector defaults them to "00:00" rather than null, so
-- an absent lobby schedule reads back as a real time rather than a null.
--
-- misaccessible is a tristate stored as text — "Y", "N" or "" for unknown — not a boolean.
--
-- The unique index on (mbankid, mbranchid) is what makes the branch id a usable handle; the plain
-- index on mbankid serves the per-bank listing, which also filters on misdeleted = false. Deletion
-- is soft: nothing removes these rows.

