-- Per-request callback registry for UTILITY transaction-requests (fifty-sixth table off
-- Lift Mapper). When a caller supplies a callback_url on a UTILITY payment, OBP persists
-- a row here and fires a fire-and-forget POST of the final result via
-- UtilityCallbackDispatcher. Distinct from the account-event webhook system: this is a
-- one-shot callback bound to a single transaction request.
--
-- One unique index on callbackid, one plain index on transactionrequestid, confirmed
-- against a booted instance's information_schema.

CREATE TABLE "PUBLIC"."UTILITYPAYMENTCALLBACK"(
    "CREATEDBYUSERID" CHARACTER VARYING(255),
    "CALLBACKID" CHARACTER VARYING(64),
    "CALLBACKURL" CHARACTER VARYING(2048),
    "IDENTIFIERTYPE" CHARACTER VARYING(64),
    "IDENTIFIER" CHARACTER VARYING(255),
    "FROMBANKID" CHARACTER VARYING(255),
    "FROMACCOUNTID" CHARACTER VARYING(255),
    "STATUS" CHARACTER VARYING(32),
    "ATTEMPTS" INTEGER,
    "RESPONSECODE" CHARACTER VARYING(32),
    "CREATIONDATE" TIMESTAMP,
    "LASTATTEMPTDATE" TIMESTAMP,
    "TRANSACTIONREQUESTID" CHARACTER VARYING(64),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."UTILITYPAYMENTCALLBACK" ADD CONSTRAINT "PUBLIC"."UTILITYPAYMENTCALLBACK_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."UTILITYPAYMENTCALLBACK_CALLBACKID" ON "PUBLIC"."UTILITYPAYMENTCALLBACK"("CALLBACKID" NULLS FIRST);
CREATE INDEX "PUBLIC"."UTILITYPAYMENTCALLBACK_TRANSACTIONREQUESTID" ON "PUBLIC"."UTILITYPAYMENTCALLBACK"("TRANSACTIONREQUESTID" NULLS FIRST);
