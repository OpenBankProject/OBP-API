-- Customer messages and per-bank transaction-request-type charges.
--
-- MAPPEDCUSTOMERMESSAGE has TWO owner columns and they are not interchangeable. user_c holds
-- RESOURCEUSER's numeric key and is written only by the deprecated addMessage path;
-- `customer` holds MAPPEDCUSTOMER's numeric key and is written only by createCustomerMessage.
-- Each read filters on exactly one of them, so a message created one way is invisible to the other
-- reader. That is the existing behaviour and the reason the deprecation note on `user` exists;
-- reproduced rather than unified here.
--
-- MAPPEDTRANSACTIONREQUESTTYPECHARGE has no index beyond its primary key, though the only read
-- filters on (mbankid, mtransactionrequesttypeid) and expects at most one row. Nothing enforces
-- that. Pre-existing; reproduced with id ASC pinning which row a lookup sees.

CREATE TABLE "PUBLIC"."MAPPEDCUSTOMERMESSAGE"(
    "MMESSAGEID" CHARACTER VARYING(36),
    "MFROMPERSON" CHARACTER VARYING(64),
    "MFROMDEPARTMENT" CHARACTER VARYING(64),
    "MMESSAGE" CHARACTER VARYING(1024),
    "MTRANSPORT" CHARACTER VARYING(64),
    "BANK" CHARACTER VARYING(44),
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "CUSTOMER" BIGINT,
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL,
    "USER_C" BIGINT
);
ALTER TABLE "PUBLIC"."MAPPEDCUSTOMERMESSAGE" ADD CONSTRAINT "PUBLIC"."MAPPEDCUSTOMERMESSAGE_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDCUSTOMERMESSAGE_CUSTOMER" ON "PUBLIC"."MAPPEDCUSTOMERMESSAGE"("CUSTOMER" NULLS FIRST);
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDCUSTOMERMESSAGE_MMESSAGEID" ON "PUBLIC"."MAPPEDCUSTOMERMESSAGE"("MMESSAGEID" NULLS FIRST);
CREATE INDEX "PUBLIC"."MAPPEDCUSTOMERMESSAGE_USER_C" ON "PUBLIC"."MAPPEDCUSTOMERMESSAGE"("USER_C" NULLS FIRST);

CREATE TABLE "PUBLIC"."MAPPEDTRANSACTIONREQUESTTYPECHARGE"(
    "MCHARGECURRENCY" CHARACTER VARYING(3),
    "MCHARGEAMOUNT" CHARACTER VARYING(32),
    "MCHARGESUMMARY" CHARACTER VARYING(255),
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "MBANKID" CHARACTER VARYING(44),
    "MTRANSACTIONREQUESTTYPEID" CHARACTER VARYING(44),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDTRANSACTIONREQUESTTYPECHARGE" ADD CONSTRAINT "PUBLIC"."MAPPEDTRANSACTIONREQUESTTYPECHARGE_PK" PRIMARY KEY("ID");
