-- Dynamic endpoints: one row per uploaded OpenAPI document.
--
-- bankid genuinely holds NULL for system-level endpoints — create writes bankId.getOrElse(null) and
-- the reader turns null-or-empty back into None — so it is bound as an Option rather than a bare
-- String.
--
-- Only dynamicendpointid is unique. Every read and the delete accept an optional bank id that
-- merely narrows the match, so a system-level lookup finds a bank-level row with the same id and
-- vice versa is prevented only by the id being generated. Pre-existing; reproduced as-is.

CREATE TABLE "PUBLIC"."DYNAMICENDPOINT"(
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "DYNAMICENDPOINTID" CHARACTER VARYING(36),
    "SWAGGERSTRING" CHARACTER VARYING(1000000000),
    "USERID" CHARACTER VARYING(255),
    "BANKID" CHARACTER VARYING(255),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."DYNAMICENDPOINT" ADD CONSTRAINT "PUBLIC"."DYNAMICENDPOINT_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."DYNAMICENDPOINT_DYNAMICENDPOINTID" ON "PUBLIC"."DYNAMICENDPOINT"("DYNAMICENDPOINTID" NULLS FIRST);
