    "DATESIGNED" TIMESTAMP,
    "DATESTARTS" TIMESTAMP,
    "DATEEXPIRES" TIMESTAMP,
    "ACTIVE" BOOLEAN,
    "COUNTERPARTYID" CHARACTER VARYING(44),
    "CUSTOMERID" CHARACTER VARYING(44),
    "DATECANCELLED" TIMESTAMP,
    "DIRECTDEBITID" CHARACTER VARYING(44),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."DIRECTDEBIT" ADD CONSTRAINT "PUBLIC"."DIRECTDEBIT_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."DIRECTDEBIT_BANKID_ACCOUNTID_CUSTOMERID_COUNTERPARTYID" ON "PUBLIC"."DIRECTDEBIT"("BANKID" NULLS FIRST, "ACCOUNTID" NULLS FIRST, "CUSTOMERID" NULLS FIRST, "COUNTERPARTYID" NULLS FIRST);

