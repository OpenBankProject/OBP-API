-- Product collections (and their items), direct debits, and standing orders.
--
--   * MAPPEDPRODUCTCOLLECTION(mcollectioncode, mproductcode) and
--     MAPPEDPRODUCTCOLLECTIONITEM(mcollectioncode, mmemberproductcode) keep a collection from
--     listing the same product twice. getOrCreate* deletes the collection's rows and re-inserts,
--     so the constraint also catches a caller passing the same code twice in one list.
--
--   * DIRECTDEBIT(bankid, accountid, customerid, counterpartyid) is a real guard, not an index for
--     speed: it is what stops a second direct debit being set up for the same customer and
--     counterparty on one account. createDirectDebit wraps the insert in tryo, so the violation
--     surfaces to the caller as a Failure rather than an exception.
--
--   * STANDINGORDER deliberately has no unique index — repeat standing orders between the same
--     parties are legitimate (different amounts, schedules, or start dates), so nothing constrains
--     the tuple.
--
-- datecancelled is written by no code path on either table and so is always NULL; the traits type
-- it as a bare Date, so the readers map the absent value back to null rather than pretending it is
-- present. dateexpires is genuinely optional and behaves the same way.
--
-- standingorder.amountvalue is a BIGINT holding the amount in the currency's smallest unit; the
-- provider converts on the way in and back out. Reading it as a decimal amount without that
-- conversion would be wrong by a factor of 100 for most currencies.

CREATE TABLE "PUBLIC"."MAPPEDPRODUCTCOLLECTION"(
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "MCOLLECTIONCODE" CHARACTER VARYING(50),
    "MPRODUCTCODE" CHARACTER VARYING(50),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDPRODUCTCOLLECTION" ADD CONSTRAINT "PUBLIC"."MAPPEDPRODUCTCOLLECTION_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDPRODUCTCOLLECTION_MCOLLECTIONCODE_MPRODUCTCODE" ON "PUBLIC"."MAPPEDPRODUCTCOLLECTION"("MCOLLECTIONCODE" NULLS FIRST, "MPRODUCTCODE" NULLS FIRST);

CREATE TABLE "PUBLIC"."MAPPEDPRODUCTCOLLECTIONITEM"(
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "MCOLLECTIONCODE" CHARACTER VARYING(50),
    "MMEMBERPRODUCTCODE" CHARACTER VARYING(50),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDPRODUCTCOLLECTIONITEM" ADD CONSTRAINT "PUBLIC"."MAPPEDPRODUCTCOLLECTIONITEM_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDPRODUCTCOLLECTIONITEM_MCOLLECTIONCODE_MMEMBERPRODUCTCODE" ON "PUBLIC"."MAPPEDPRODUCTCOLLECTIONITEM"("MCOLLECTIONCODE" NULLS FIRST, "MMEMBERPRODUCTCODE" NULLS FIRST);

CREATE TABLE "PUBLIC"."DIRECTDEBIT"(
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
