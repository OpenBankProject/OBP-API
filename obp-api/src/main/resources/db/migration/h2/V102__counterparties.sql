-- Counterparties and their metadata.
--
-- Two different things share the word "counterparty" here, and only one of them lives in
-- MAPPEDCOUNTERPARTY:
--   * an EXPLICIT counterparty, created through the create-counterparty endpoint, is a row in
--     MAPPEDCOUNTERPARTY;
--   * an IMPLICIT counterparty, derived while reading transactions, is never stored - but a
--     MAPPEDCOUNTERPARTYMETADATA row is created for it so aliases, tags and locations have
--     somewhere to live.
-- That is why the metadata table is keyed by COUNTERPARTYID only and carries no foreign key to
-- MAPPEDCOUNTERPARTY: for most rows there is nothing to point at.
--
-- MAPPEDCOUNTERPARTY has two unique indexes: on the counterparty id, and on
-- (name, this bank, this account, this view) - the same name may not be used twice for the same
-- account and view. Two further unique indexes over the routing columns are commented out in the
-- entity and were never created, which is why a counterparty can be looked up by IBAN but not
-- uniquely: getCounterpartyByIban takes the newest match.
--
-- CORPORATELOCATION and PHYSICALLOCATION hold the id of a MAPPEDCOUNTERPARTYWHERETAG row, or NULL.
-- Schemifier built them as plain indexed BIGINT columns rather than declared foreign keys, so
-- deleting a where-tag leaves the pointer dangling; readers treat a missing tag as no tag.
--
-- USER_C and DATE_C in the where-tag table carry the Schemifier suffix for reserved words: the
-- entity's fields are `user` and `date`.

CREATE TABLE "PUBLIC"."MAPPEDCOUNTERPARTY"(
    "CREATEDAT" TIMESTAMP,
    "UPDATEDAT" TIMESTAMP,
    "MDESCRIPTION" CHARACTER VARYING(2000),
    "MCOUNTERPARTYID" CHARACTER VARYING(44),
    "MNAME" CHARACTER VARYING(36),
    "MTHISBANKID" CHARACTER VARYING(36),
    "MTHISACCOUNTID" CHARACTER VARYING(64),
    "MTHISVIEWID" CHARACTER VARYING(36),
    "MCREATEDBYUSERID" CHARACTER VARYING(36),
    "MISBENEFICIARY" BOOLEAN,
    "MCURRENCY" CHARACTER VARYING(255),
    "MOTHERBANKROUTINGSCHEME" CHARACTER VARYING(255),
    "MOTHERBANKROUTINGADDRESS" CHARACTER VARYING(255),
    "MOTHERBRANCHROUTINGSCHEME" CHARACTER VARYING(255),
    "MOTHERBRANCHROUTINGADDRESS" CHARACTER VARYING(255),
    "MOTHERACCOUNTROUTINGSCHEME" CHARACTER VARYING(255),
    "MOTHERACCOUNTROUTINGADDRESS" CHARACTER VARYING(255),
    "MOTHERACCOUNTSECONDARYROUTINGSCHEME" CHARACTER VARYING(255),
    "MOTHERACCOUNTSECONDARYROUTINGADDRESS" CHARACTER VARYING(255),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDCOUNTERPARTY" ADD CONSTRAINT "PUBLIC"."MAPPEDCOUNTERPARTY_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDCOUNTERPARTY_MCOUNTERPARTYID" ON "PUBLIC"."MAPPEDCOUNTERPARTY"("MCOUNTERPARTYID" NULLS FIRST);
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDCOUNTERPARTY_MNAME_MTHISBANKID_MTHISACCOUNTID_MTHISVIEWID" ON "PUBLIC"."MAPPEDCOUNTERPARTY"("MNAME" NULLS FIRST, "MTHISBANKID" NULLS FIRST, "MTHISACCOUNTID" NULLS FIRST, "MTHISVIEWID" NULLS FIRST);

CREATE TABLE "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA"(
    "COUNTERPARTYID" CHARACTER VARYING(44),
    "THISBANKID" CHARACTER VARYING(44),
    "THISACCOUNTID" CHARACTER VARYING(64),
    "MOREINFO" CHARACTER VARYING(255),
    "COUNTERPARTYNAME" CHARACTER VARYING(255),
    "CREATEDAT" TIMESTAMP,
    "UPDATEDAT" TIMESTAMP,
    "PUBLICALIAS" CHARACTER VARYING(64),
    "PRIVATEALIAS" CHARACTER VARYING(64),
    "CORPORATELOCATION" BIGINT,
    "PHYSICALLOCATION" BIGINT,
    "IMAGEURL" CHARACTER VARYING(2000),
    "OPENCORPORATESURL" CHARACTER VARYING(2000),
    "URL" CHARACTER VARYING(2000),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA" ADD CONSTRAINT "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA_CORPORATELOCATION" ON "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA"("CORPORATELOCATION" NULLS FIRST);
CREATE INDEX "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA_PHYSICALLOCATION" ON "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA"("PHYSICALLOCATION" NULLS FIRST);
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA_COUNTERPARTYID" ON "PUBLIC"."MAPPEDCOUNTERPARTYMETADATA"("COUNTERPARTYID" NULLS FIRST);

CREATE TABLE "PUBLIC"."MAPPEDCOUNTERPARTYWHERETAG"(
    "CREATEDAT" TIMESTAMP,
    "UPDATEDAT" TIMESTAMP,
    "GEOLONGITUDE" DOUBLE PRECISION,
    "GEOLATITUDE" DOUBLE PRECISION,
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL,
    "USER_C" BIGINT,
    "DATE_C" TIMESTAMP
);
ALTER TABLE "PUBLIC"."MAPPEDCOUNTERPARTYWHERETAG" ADD CONSTRAINT "PUBLIC"."MAPPEDCOUNTERPARTYWHERETAG_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDCOUNTERPARTYWHERETAG_USER_C" ON "PUBLIC"."MAPPEDCOUNTERPARTYWHERETAG"("USER_C" NULLS FIRST);
