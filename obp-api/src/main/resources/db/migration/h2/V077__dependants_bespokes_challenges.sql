-- Customer dependants, counterparty bespokes, and expected challenge answers.
--
-- MAPPEDCUSTOMERDEPENDANT.mcustomer and MAPPEDCOUNTERPARTYBESPOKE.mcounterparty are BIGINTs holding
-- the parent row's numeric primary key, not the public customer_id / counterparty_id. Both
-- providers already take that numeric key as their argument, so the values pass through unchanged —
-- but a reader who assumes these are public ids will match nothing.
--
-- EXPECTEDCHALLENGEANSWER's unique index on challengeid is load-bearing for payment security: the
-- compare-and-set that flips successful false -> true keys off it, and that CAS is what stops one
-- challenge green-lighting a payment twice. successful is stored as SUCCESSFUL_C because SUCCESSFUL
-- collides with a SQL reserved word, which is why the column name does not match the field.
--
-- The optional challenge columns hold '' rather than NULL when absent, because Mapper wrote
-- MappedString's default. That distinction is visible above the store: consentid and basketid are
-- surfaced with a bare Option, so an absent value reads as Some("") rather than None, while the
-- three PSD2 dynamic-linking columns filter empties out and do read as None. Both behaviours are
-- preserved verbatim.

CREATE TABLE "PUBLIC"."MAPPEDCUSTOMERDEPENDANT"(
    "MCUSTOMER" BIGINT,
    "MDATEOFBIRTH" TIMESTAMP,
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDCUSTOMERDEPENDANT" ADD CONSTRAINT "PUBLIC"."MAPPEDCUSTOMERDEPENDANT_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDCUSTOMERDEPENDANT_MCUSTOMER" ON "PUBLIC"."MAPPEDCUSTOMERDEPENDANT"("MCUSTOMER" NULLS FIRST);

CREATE TABLE "PUBLIC"."MAPPEDCOUNTERPARTYBESPOKE"(
    "MKEY" CHARACTER VARYING(255),
    "MVAULE" CHARACTER VARYING(255),
    "MCOUNTERPARTY" BIGINT,
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDCOUNTERPARTYBESPOKE" ADD CONSTRAINT "PUBLIC"."MAPPEDCOUNTERPARTYBESPOKE_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDCOUNTERPARTYBESPOKE_MCOUNTERPARTY" ON "PUBLIC"."MAPPEDCOUNTERPARTYBESPOKE"("MCOUNTERPARTY" NULLS FIRST);

CREATE TABLE "PUBLIC"."EXPECTEDCHALLENGEANSWER"(
    "BASKETID" CHARACTER VARYING(100),
    "CONSENTID" CHARACTER VARYING(100),
    "CHALLENGEID" CHARACTER VARYING(36),
    "CHALLENGETYPE" CHARACTER VARYING(100),
    "EXPECTEDANSWER" CHARACTER VARYING(50),
    "EXPECTEDUSERID" CHARACTER VARYING(36),
    "SALT" CHARACTER VARYING(50),
    "SUCCESSFUL_C" BOOLEAN,
    "SCAMETHOD" CHARACTER VARYING(100),
    "SCASTATUS" CHARACTER VARYING(100),
    "ATTEMPTCOUNTER" INTEGER,
    "CHALLENGEPURPOSE" CHARACTER VARYING(2000),
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "TRANSACTIONREQUESTID" CHARACTER VARYING(36),
    "AUTHENTICATIONMETHODID" CHARACTER VARYING(100),
    "CHALLENGECONTEXTHASH" CHARACTER VARYING(64),
    "CHALLENGECONTEXTSTRUCTURE" CHARACTER VARYING(500),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."EXPECTEDCHALLENGEANSWER" ADD CONSTRAINT "PUBLIC"."EXPECTEDCHALLENGEANSWER_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."EXPECTEDCHALLENGEANSWER_CHALLENGEID" ON "PUBLIC"."EXPECTEDCHALLENGEANSWER"("CHALLENGEID" NULLS FIRST);
