-- Routing schemes, per-bank routing-scheme support, and ABAC rules.
--
--   * ROUTINGSCHEME(scheme) is unique, which is what makes `scheme` usable as the handle every
--     read, update and the soft delete key off.
--
--   * BANKSUPPORTEDROUTINGSCHEME(bankid, scheme) is unique, which is what makes
--     putBankSupportedRoutingScheme an upsert rather than an append: it looks the pair up and
--     updates, or inserts when absent.
--
--   * ABACRULE has three plain indexes and no unique one, though abacRuleId is the handle the
--     update and delete key off and getAbacRuleByName reads by rulename. Two rules may therefore
--     share a name. Pre-existing; reproduced with id ASC pinning which one a lookup sees.
--
-- Deleting a routing scheme is a soft delete — status goes to RETIRED and the row stays, so
-- historical addresses can still be resolved. Nothing removes these rows.
--
-- downstreamrails and secondaryaddresspattern hold '' rather than NULL when absent, and the
-- readers turn '' into Nil / None respectively.

CREATE TABLE "PUBLIC"."ROUTINGSCHEME"(
    "CREATEDBYUSERID" CHARACTER VARYING(255),
    "SCHEME" CHARACTER VARYING(64),
    "COUNTRY" CHARACTER VARYING(8),
    "ADDRESSPATTERN" CHARACTER VARYING(1024),
    "EXAMPLEADDRESS" CHARACTER VARYING(255),
    "DESCRIPTION" CHARACTER VARYING(1000000000),
    "DOWNSTREAMRAILS" CHARACTER VARYING(512),
    "CREATIONDATE" TIMESTAMP,
    "LASTUPDATE" TIMESTAMP,
    "STATUS" CHARACTER VARYING(16),
    "SECONDARYADDRESSPATTERN" CHARACTER VARYING(1024),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL,
    "CATEGORY" CHARACTER VARYING(16)
);
ALTER TABLE "PUBLIC"."ROUTINGSCHEME" ADD CONSTRAINT "PUBLIC"."ROUTINGSCHEME_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."ROUTINGSCHEME_SCHEME" ON "PUBLIC"."ROUTINGSCHEME"("SCHEME" NULLS FIRST);

CREATE TABLE "PUBLIC"."BANKSUPPORTEDROUTINGSCHEME"(
    "BANKID" CHARACTER VARYING(255),
    "SCHEME" CHARACTER VARYING(64),
    "ENABLED" BOOLEAN,
    "BANKNOTES" CHARACTER VARYING(1024),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."BANKSUPPORTEDROUTINGSCHEME" ADD CONSTRAINT "PUBLIC"."BANKSUPPORTEDROUTINGSCHEME_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."BANKSUPPORTEDROUTINGSCHEME_BANKID" ON "PUBLIC"."BANKSUPPORTEDROUTINGSCHEME"("BANKID" NULLS FIRST);
CREATE UNIQUE INDEX "PUBLIC"."BANKSUPPORTEDROUTINGSCHEME_BANKID_SCHEME" ON "PUBLIC"."BANKSUPPORTEDROUTINGSCHEME"("BANKID" NULLS FIRST, "SCHEME" NULLS FIRST);

CREATE TABLE "PUBLIC"."ABACRULE"(
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "CREATEDBYUSERID" CHARACTER VARYING(255),
    "DESCRIPTION" CHARACTER VARYING(1000000000),
    "UPDATEDBYUSERID" CHARACTER VARYING(255),
    "ABACRULEID" CHARACTER VARYING(255),
    "RULENAME" CHARACTER VARYING(255),
    "ISACTIVE" BOOLEAN,
    "RULECODE" CHARACTER VARYING(1000000000),
    "POLICY" CHARACTER VARYING(1000000000),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."ABACRULE" ADD CONSTRAINT "PUBLIC"."ABACRULE_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."ABACRULE_ABACRULEID" ON "PUBLIC"."ABACRULE"("ABACRULEID" NULLS FIRST);
CREATE INDEX "PUBLIC"."ABACRULE_CREATEDBYUSERID" ON "PUBLIC"."ABACRULE"("CREATEDBYUSERID" NULLS FIRST);
CREATE INDEX "PUBLIC"."ABACRULE_RULENAME" ON "PUBLIC"."ABACRULE"("RULENAME" NULLS FIRST);
