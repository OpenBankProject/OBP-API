-- Account attribute table, forty-second table off Lift Mapper. mAccountAttributeId is a
-- MappedUUID (36 chars); mBankIdId/mAccountId are UUIDString (44 chars).
--
-- No unique index - only plain indexes on mAccountId and mAccountAttributeId, matching the
-- entity's own dbIndexes (Index(mAccountId) :: Index(mAccountAttributeId)), confirmed against a
-- booted instance's information_schema.indexes.

CREATE TABLE "PUBLIC"."MAPPEDACCOUNTATTRIBUTE"(
    "MVALUE" CHARACTER VARYING(255),
    "MBANKIDID" CHARACTER VARYING(44),
    "MACCOUNTID" CHARACTER VARYING(44),
    "MCODE" CHARACTER VARYING(50),
    "MNAME" CHARACTER VARYING(50),
    "MTYPE" CHARACTER VARYING(50),
    "MACCOUNTATTRIBUTEID" CHARACTER VARYING(36),
    "MPRODUCTINSTANCECODE" CHARACTER VARYING(255),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDACCOUNTATTRIBUTE" ADD CONSTRAINT "PUBLIC"."MAPPEDACCOUNTATTRIBUTE_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDACCOUNTATTRIBUTE_MACCOUNTID" ON "PUBLIC"."MAPPEDACCOUNTATTRIBUTE"("MACCOUNTID" NULLS FIRST);
CREATE INDEX "PUBLIC"."MAPPEDACCOUNTATTRIBUTE_MACCOUNTATTRIBUTEID" ON "PUBLIC"."MAPPEDACCOUNTATTRIBUTE"("MACCOUNTATTRIBUTEID" NULLS FIRST);
