-- Customer addresses and entitlement requests.
--
-- MAPPEDCUSTOMERADDRESS.mcustomerid is NOT the public customer_id: it is a BIGINT holding
-- MAPPEDCUSTOMER's numeric primary key, left over from the Lift foreign key. Everything above the
-- store speaks in the public customer_id, so the queries join through mappedcustomer rather than
-- comparing the two. Reading it as if it were the public id silently matches nothing.
--
-- MAPPEDENTITLEMENTREQUEST has no unique index on (mbankid, muserid, mrolename) even though
-- getEntitlementRequest looks a row up by exactly that triple, so a user can have two outstanding
-- requests for the same role and a lookup sees one of them. Pre-existing; reproduced as-is, with
-- id ASC pinning which one.

CREATE TABLE "PUBLIC"."MAPPEDCUSTOMERADDRESS"(
    "MCUSTOMERADDRESSID" CHARACTER VARYING(36),
    "MTAGS" CHARACTER VARYING(20),
    "MCUSTOMERID" BIGINT,
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "MLINE1" CHARACTER VARYING(255),
    "MLINE2" CHARACTER VARYING(255),
    "MLINE3" CHARACTER VARYING(255),
    "MCITY" CHARACTER VARYING(255),
    "MCOUNTY" CHARACTER VARYING(255),
    "MSTATE" CHARACTER VARYING(255),
    "MPOSTCODE" CHARACTER VARYING(20),
    "MCOUNTRYCODE" CHARACTER VARYING(2),
    "MSTATUS" CHARACTER VARYING(20),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDCUSTOMERADDRESS" ADD CONSTRAINT "PUBLIC"."MAPPEDCUSTOMERADDRESS_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDCUSTOMERADDRESS_MCUSTOMERADDRESSID" ON "PUBLIC"."MAPPEDCUSTOMERADDRESS"("MCUSTOMERADDRESSID" NULLS FIRST);
CREATE INDEX "PUBLIC"."MAPPEDCUSTOMERADDRESS_MCUSTOMERID" ON "PUBLIC"."MAPPEDCUSTOMERADDRESS"("MCUSTOMERID" NULLS FIRST);

CREATE TABLE "PUBLIC"."MAPPEDENTITLEMENTREQUEST"(
    "MROLENAME" CHARACTER VARYING(255),
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "MBANKID" CHARACTER VARYING(44),
    "MUSERID" CHARACTER VARYING(44),
    "MENTITLEMENTREQUESTID" CHARACTER VARYING(36),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDENTITLEMENTREQUEST" ADD CONSTRAINT "PUBLIC"."MAPPEDENTITLEMENTREQUEST_PK" PRIMARY KEY("ID");
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDENTITLEMENTREQUEST_MENTITLEMENTREQUESTID" ON "PUBLIC"."MAPPEDENTITLEMENTREQUEST"("MENTITLEMENTREQUESTID" NULLS FIRST);
