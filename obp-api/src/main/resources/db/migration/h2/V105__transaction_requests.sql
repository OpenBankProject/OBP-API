-- Transaction requests: the payment instruction, as opposed to the transaction it eventually
-- produces. One row records what was asked for, what it costs, where it is in the challenge and
-- status flow, and - once it completes - the id of the transaction that settled it.
--
-- MTRANSACTIONIDS holds the settling transaction id (singular, despite the name) and is what
-- bulkDeleteTransactionRequestsByTransactionId matches on.
--
-- MDETAILS is the whole create body as JSON in one unbounded column. toTransactionRequest reads the
-- type-specific half of the request back out of it - IBANs, counterparty ids, agent numbers - so
-- the columns beside it are a partial, denormalised copy rather than the whole story.
--
-- The MPAYMENT* columns carry the Berlin Group periodic-payment schedule and are null for every
-- other kind of request. The MORIGINATOR_* columns carry the FATF Recommendation 16 originator and
-- today are written only by OPEN_CORRIDOR_PROMISE.
--
-- MSTARTDATE, MENDDATE and the two MPAYMENT dates are DATE, not TIMESTAMP: they are calendar dates
-- with no time of day.

CREATE TABLE "PUBLIC"."MAPPEDTRANSACTIONREQUEST"(
    "MBODY_VALUE_AMOUNT" CHARACTER VARYING(32),
    "CREATEDAT" TIMESTAMP,
    "MUSERID" CHARACTER VARYING(100),
    "UPDATEDAT" TIMESTAMP,
    "MSTATUS" CHARACTER VARYING(32),
    "MCONSUMERID" CHARACTER VARYING(100),
    "MAPISTANDARD" CHARACTER VARYING(50),
    "MAPIVERSION" CHARACTER VARYING(50),
    "MTYPE" CHARACTER VARYING(32),
    "MFROM_BANKID" CHARACTER VARYING(44),
    "MTO_BANKID" CHARACTER VARYING(44),
    "MDETAILS" CHARACTER VARYING,
    "MCHARGE_CURRENCY" CHARACTER VARYING(16),
    "MCHARGE_AMOUNT" CHARACTER VARYING(32),
    "MTRANSACTIONIDS" CHARACTER VARYING(2000),
    "MNAME" CHARACTER VARYING(140),
    "MCHARGE_SUMMARY" CHARACTER VARYING(64),
    "MPAYMENTSTARTDATE" DATE,
    "MFROM_ACCOUNTID" CHARACTER VARYING(64),
    "MCHALLENGE_ID" CHARACTER VARYING(64),
    "MTO_ACCOUNTID" CHARACTER VARYING(128),
    "MPAYMENTFREQUENCY" CHARACTER VARYING(64),
    "MTHISBANKID" CHARACTER VARYING(44),
    "MTHISVIEWID" CHARACTER VARYING(44),
    "MENDDATE" DATE,
    "MSTARTDATE" DATE,
    "MBODY_DESCRIPTION" CHARACTER VARYING(2000),
    "MTHISACCOUNTID" CHARACTER VARYING(64),
    "MCHARGE_POLICY" CHARACTER VARYING(32),
    "MISBENEFICIARY" BOOLEAN,
    "MORIGINATOR_NAME" CHARACTER VARYING(140),
    "MCOUNTERPARTYID" CHARACTER VARYING(44),
    "MPAYMENTENDDATE" DATE,
    "MONBEHALFOFUSERID" CHARACTER VARYING(100),
    "MBODY_VALUE_CURRENCY" CHARACTER VARYING(16),
    "MCONSENTREFERENCEID" CHARACTER VARYING(64),
    "MTRANSACTIONREQUESTID" CHARACTER VARYING(44),
    "MCHALLENGE_ALLOWEDATTEMPTS" INTEGER,
    "MCHALLENGE_CHALLENGETYPE" CHARACTER VARYING(100),
    "MOTHERACCOUNTROUTINGSCHEME" CHARACTER VARYING(32),
    "MOTHERACCOUNTROUTINGADDRESS" CHARACTER VARYING(128),
    "MOTHERBANKROUTINGSCHEME" CHARACTER VARYING(32),
    "MOTHERBANKROUTINGADDRESS" CHARACTER VARYING(64),
    "MORIGINATOR_ADDRESS" CHARACTER VARYING(2000),
    "MORIGINATOR_ACCOUNTROUTINGSCHEME" CHARACTER VARYING(32),
    "MORIGINATOR_ACCOUNTROUTINGADDRESS" CHARACTER VARYING(128),
    "MPAYMENTEXECUTIONRULE" CHARACTER VARYING(64),
    "MPAYMENTDAYOFEXECUTION" CHARACTER VARYING(64),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDTRANSACTIONREQUEST" ADD CONSTRAINT "PUBLIC"."MAPPEDTRANSACTIONREQUEST_PK" PRIMARY KEY("ID");
