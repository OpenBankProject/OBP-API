-- Meetings and their invitees.
--
-- mcustomeruserid and mstaffuserid are BIGINTs holding RESOURCEUSER's numeric primary key, not the
-- public user_id — the `present` accessor resolves them through a join. mstaffuserid is never
-- written (createMeeting has that line commented out), so it is always NULL and the staff user id
-- surfaces as "".
--
-- MAPPEDMEETINGINVITEE.mmappedmeeting is likewise MAPPEDMEETING's numeric key. Invitees were read
-- through a Lift OneToMany that ordered by id ascending; the replacement query keeps that order,
-- which is the order the invitees were supplied in.
--
-- MAPPEDMEETING(mmeetingid) is unique. Nothing constrains (mbankid, mmeetingid) even though
-- getMeeting reads by that pair, but the unique id makes the pair single-valued anyway.

CREATE TABLE "PUBLIC"."MAPPEDMEETING"(
    "MSTAFFUSERID" BIGINT,
    "MMEETINGID" CHARACTER VARYING(36),
    "MWHEN" TIMESTAMP,
    "MCUSTOMERUSERID" BIGINT,
    "MPROVIDERID" CHARACTER VARYING(64),
    "MPURPOSEID" CHARACTER VARYING(64),
    "MSESSIONID" CHARACTER VARYING(255),
    "MCUSTOMERTOKEN" CHARACTER VARYING(255),
    "MSTAFFTOKEN" CHARACTER VARYING(255),
    "MCREATORNAME" CHARACTER VARYING(255),
    "MCREATORPHONE" CHARACTER VARYING(32),
    "MCREATOREMAIL" CHARACTER VARYING(100),
    "UPDATEDAT" TIMESTAMP,
    "CREATEDAT" TIMESTAMP,
    "MBANKID" CHARACTER VARYING(44),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDMEETING" ADD CONSTRAINT "PUBLIC"."MAPPEDMEETING_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDMEETING_MCUSTOMERUSERID" ON "PUBLIC"."MAPPEDMEETING"("MCUSTOMERUSERID" NULLS FIRST);
CREATE UNIQUE INDEX "PUBLIC"."MAPPEDMEETING_MMEETINGID" ON "PUBLIC"."MAPPEDMEETING"("MMEETINGID" NULLS FIRST);
CREATE INDEX "PUBLIC"."MAPPEDMEETING_MSTAFFUSERID" ON "PUBLIC"."MAPPEDMEETING"("MSTAFFUSERID" NULLS FIRST);

CREATE TABLE "PUBLIC"."MAPPEDMEETINGINVITEE"(
    "MMAPPEDMEETING" BIGINT,
    "MPHONE" CHARACTER VARYING(255),
    "MEMAIL" CHARACTER VARYING(100),
    "MNAME" CHARACTER VARYING(255),
    "MSTATUS" CHARACTER VARYING(255),
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL
);
ALTER TABLE "PUBLIC"."MAPPEDMEETINGINVITEE" ADD CONSTRAINT "PUBLIC"."MAPPEDMEETINGINVITEE_PK" PRIMARY KEY("ID");
CREATE INDEX "PUBLIC"."MAPPEDMEETINGINVITEE_MMAPPEDMEETING" ON "PUBLIC"."MAPPEDMEETINGINVITEE"("MMAPPEDMEETING" NULLS FIRST);
