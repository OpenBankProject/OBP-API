        otherAccountRoutingAddress = otherAccountRoutingAddress,
        otherBankRoutingScheme = StringHelpers.snakify(otherBankRoutingScheme).toUpperCase,
        otherBankRoutingAddress = otherBankRoutingAddress,
        otherBranchRoutingScheme = StringHelpers.snakify(otherBranchRoutingScheme).toUpperCase,
        otherBranchRoutingAddress = otherBranchRoutingAddress,
        isBeneficiary = isBeneficiary,
        description = description,
        currency = currency,
        otherAccountSecondaryRoutingScheme = otherAccountSecondaryRoutingScheme,
        otherAccountSecondaryRoutingAddress = otherAccountSecondaryRoutingAddress)

      // The bespoke rows are written by the provider and read back through it (see `bespoke`
      // below), so they are stored here directly. The former `mBespoke += ...` fed a Lift
      // OneToMany collection on an already-saved parent that was never saved again and never
      // read from, so it persisted nothing.
      CounterpartyBespokes.counterpartyBespokers.vend
        .createCounterpartyBespokes(mappedCounterparty.counterpartyPrimaryKey, bespoke)

      mappedCounterparty
    }
  }

