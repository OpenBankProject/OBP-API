  private type Row = (Long, Option[String], Option[String], Option[String], Option[String],
    Option[String], Option[String], Option[String], Option[String], Option[String], Option[String],
    Option[String], Option[String], Option[String], Option[String], Option[Boolean], Option[String],
    Option[String])

  private def fromRow(row: Row): MappedCounterparty = row match {
    case (id, counterpartyId, name, createdByUserId, thisBankId, thisAccountId, thisViewId,
          otherBankRoutingScheme, otherBankRoutingAddress, otherBranchRoutingScheme,
          otherBranchRoutingAddress, otherAccountRoutingScheme, otherAccountRoutingAddress,
          otherAccountSecondaryRoutingScheme, otherAccountSecondaryRoutingAddress, isBeneficiary,
          description, currency) =>
      MappedCounterparty(id, counterpartyId.orNull, name.orNull, createdByUserId.orNull,
        thisBankId.orNull, thisAccountId.orNull, thisViewId.orNull,
        otherBankRoutingScheme.orNull, otherBankRoutingAddress.orNull,
        otherBranchRoutingScheme.orNull, otherBranchRoutingAddress.orNull,
        otherAccountRoutingScheme.orNull, otherAccountRoutingAddress.orNull,
        otherAccountSecondaryRoutingScheme.orNull, otherAccountSecondaryRoutingAddress.orNull,
        isBeneficiary.getOrElse(false), description.orNull,
        // currency alone reads back "" rather than null for a NULL column: the entity exposed it
        // through the field's toString, which renders a null value as the empty string, and
        // callers compare it against a currency code.
        currency.getOrElse(""))
  }

  private def query(condition: Fragment): List[MappedCounterparty] =
    DoobieUtil.runQuery((selectColumns ++ condition).query[Row].to[List]).map(fromRow)

  private def opt(value: String): Option[String] = Option(value)

  private def one(condition: Fragment): Box[MappedCounterparty] =
    query(condition ++ fr"ORDER BY id ASC LIMIT 1").headOption match {
      case Some(row) => Full(row)
      case None => Empty
    }

  def findByCounterpartyId(counterpartyId: String): Box[MappedCounterparty] =
    one(fr"WHERE mcounterpartyid = ${opt(counterpartyId)}")

  /** Nothing makes the IBAN unique, so the newest row wins. */
  def findNewestBySecondaryRoutingAddress(iban: String): Box[MappedCounterparty] =
    query(fr"WHERE motheraccountsecondaryroutingaddress = ${opt(iban)} ORDER BY id DESC LIMIT 1")
      .headOption match {
        case Some(row) => Full(row)
        case None => Empty
      }

  def findBySecondaryRoutingAddressAndAccount(iban: String, thisBankId: String,
                                              thisAccountId: String): Box[MappedCounterparty] =
    one(fr"""WHERE motheraccountsecondaryroutingaddress = ${opt(iban)}
               AND mthisbankid = ${opt(thisBankId)} AND mthisaccountid = ${opt(thisAccountId)}""")

  def findByRoutings(otherBankRoutingScheme: String, otherBankRoutingAddress: String,
                     otherBranchRoutingScheme: String, otherBranchRoutingAddress: String,
                     otherAccountRoutingScheme: String,
                     otherAccountRoutingAddress: String): Box[MappedCounterparty] =
    one(fr"""WHERE motherbankroutingscheme = ${opt(otherBankRoutingScheme)}
               AND motherbankroutingaddress = ${opt(otherBankRoutingAddress)}
               AND motherbranchroutingscheme = ${opt(otherBranchRoutingScheme)}
               AND motherbranchroutingaddress = ${opt(otherBranchRoutingAddress)}
               AND motheraccountroutingscheme = ${opt(otherAccountRoutingScheme)}
               AND motheraccountroutingaddress = ${opt(otherAccountRoutingAddress)}""")

  def findBySecondaryRouting(otherAccountSecondaryRoutingScheme: String,
                             otherAccountSecondaryRoutingAddress: String): Box[MappedCounterparty] =
    one(fr"""WHERE motheraccountsecondaryroutingscheme = ${opt(otherAccountSecondaryRoutingScheme)}
               AND motheraccountsecondaryroutingaddress = ${opt(otherAccountSecondaryRoutingAddress)}""")

  def findAllByAccountAndView(thisBankId: String, thisAccountId: String,
                              thisViewId: String): List[MappedCounterparty] =
    query(fr"""WHERE mthisaccountid = ${opt(thisAccountId)} AND mthisbankid = ${opt(thisBankId)}
                 AND mthisviewid = ${opt(thisViewId)}""")

  def findByNameAndAccountAndView(name: String, thisBankId: String, thisAccountId: String,
                                  thisViewId: String): Box[MappedCounterparty] =
    one(fr"""WHERE mname = ${opt(name)} AND mthisbankid = ${opt(thisBankId)}
               AND mthisaccountid = ${opt(thisAccountId)} AND mthisviewid = ${opt(thisViewId)}""")

  def insert(counterpartyId: String, name: String, createdByUserId: String, thisBankId: String,
             thisAccountId: String, thisViewId: String, otherAccountRoutingScheme: String,
             otherAccountRoutingAddress: String, otherBankRoutingScheme: String,
             otherBankRoutingAddress: String, otherBranchRoutingScheme: String,
             otherBranchRoutingAddress: String, isBeneficiary: Boolean, description: String,
             currency: String, otherAccountSecondaryRoutingScheme: String,
             otherAccountSecondaryRoutingAddress: String): MappedCounterparty = {
    val now = new java.sql.Timestamp(System.currentTimeMillis())
    val id = DoobieUtil.runUpdate(
      sql"""INSERT INTO mappedcounterparty
            (mcounterpartyid, mname, mcreatedbyuserid, mthisbankid, mthisaccountid, mthisviewid,
             motherbankroutingscheme, motherbankroutingaddress, motherbranchroutingscheme,
             motherbranchroutingaddress, motheraccountroutingscheme, motheraccountroutingaddress,
             motheraccountsecondaryroutingscheme, motheraccountsecondaryroutingaddress,
             misbeneficiary, mdescription, mcurrency, createdat, updatedat)
            VALUES (${opt(counterpartyId)}, ${opt(name)}, ${opt(createdByUserId)},
             ${opt(thisBankId)}, ${opt(thisAccountId)}, ${opt(thisViewId)},
             ${opt(otherBankRoutingScheme)}, ${opt(otherBankRoutingAddress)},
             ${opt(otherBranchRoutingScheme)}, ${opt(otherBranchRoutingAddress)},
             ${opt(otherAccountRoutingScheme)}, ${opt(otherAccountRoutingAddress)},
             ${opt(otherAccountSecondaryRoutingScheme)},
             ${opt(otherAccountSecondaryRoutingAddress)},
             $isBeneficiary, ${opt(description)}, ${opt(currency)}, $now, $now)"""
        .update.withUniqueGeneratedKeys[Long]("id"))
    MappedCounterparty(id, counterpartyId, name, createdByUserId, thisBankId, thisAccountId,
      thisViewId, otherBankRoutingScheme, otherBankRoutingAddress, otherBranchRoutingScheme,
      otherBranchRoutingAddress, otherAccountRoutingScheme, otherAccountRoutingAddress,
      otherAccountSecondaryRoutingScheme, otherAccountSecondaryRoutingAddress, isBeneficiary,
      description, currency)
  }

  def deleteById(counterpartyPrimaryKey: Long): Boolean =
    DoobieUtil.runUpdate(
      sql"DELETE FROM mappedcounterparty WHERE id = $counterpartyPrimaryKey".update.run) > 0

  def deleteAll(): Unit = {
    DoobieUtil.runUpdate(sql"DELETE FROM mappedcounterparty".update.run)
    ()
  }
}
