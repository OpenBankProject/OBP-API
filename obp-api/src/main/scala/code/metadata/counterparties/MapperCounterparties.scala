/**
 * Everything an account's owner has attached to one counterparty: the aliases shown instead of the
 * real name, free-text notes, and two map pins.
 *
 * A row exists for every counterparty an account has seen, including the implicit ones that are
 * never stored as counterparties themselves — which is why it is keyed by counterparty id and
 * carries the bank and account it belongs to rather than a foreign key.
 *
 * The mutator members are `val`s of function type because the trait declares them that way.
 * Each writes straight through to the row identified by `metadataPrimaryKey` and returns whether
 * the write succeeded, so a value read from an instance held across a write is stale — as it was
 * with Mapper.
 */
case class MappedCounterpartyMetadata(
  metadataPrimaryKey: Long,
  counterpartyId: String,
  counterpartyName: String,
  thisBankId: String,
  thisAccountId: String,
  publicAlias: String,
  privateAlias: String,
  moreInfo: String,
  url: String,
  imageUrl: String,
  openCorporatesUrl: String,
  corporateLocationId: Option[Long],
  physicalLocationId: Option[Long]
) extends CounterpartyMetadata {

  override def getCounterpartyId: String = counterpartyId
  override def getCounterpartyName: String = counterpartyName
  override def getPublicAlias: String = publicAlias
  override def getPrivateAlias: String = privateAlias
  override def getMoreInfo: String = moreInfo
  override def getUrl: String = url
  override def getImageURL: String = imageUrl
  override def getOpenCorporatesURL: String = openCorporatesUrl

  override def getCorporateLocation: Option[GeoTag] =
    corporateLocationId.flatMap(MappedCounterpartyWhereTag.findById)
  override def getPhysicalLocation: Option[GeoTag] =
    physicalLocationId.flatMap(MappedCounterpartyWhereTag.findById)

  override val addPrivateAlias: String => Boolean =
    x => MappedCounterpartyMetadata.setText(metadataPrimaryKey, fr"privatealias", x)
  override val addURL: String => Boolean =
    x => MappedCounterpartyMetadata.setText(metadataPrimaryKey, fr"url", x)
  override val addMoreInfo: String => Boolean =
    x => MappedCounterpartyMetadata.setText(metadataPrimaryKey, fr"moreinfo", x)
  override val addPublicAlias: String => Boolean =
    x => MappedCounterpartyMetadata.setText(metadataPrimaryKey, fr"publicalias", x)
  override val addOpenCorporatesURL: String => Boolean =
    x => MappedCounterpartyMetadata.setText(metadataPrimaryKey, fr"opencorporatesurl", x)
  override val addImageURL: String => Boolean =
    x => MappedCounterpartyMetadata.setText(metadataPrimaryKey, fr"imageurl", x)

  override val addCorporateLocation: (UserPrimaryKey, Date, Double, Double) => Boolean =
    (userId, datePosted, longitude, latitude) =>
      MappedCounterpartyMetadata.setLocation(metadataPrimaryKey, fr"corporatelocation",
        corporateLocationId, userId, datePosted, longitude, latitude)
  override val addPhysicalLocation: (UserPrimaryKey, Date, Double, Double) => Boolean =
    (userId, datePosted, longitude, latitude) =>
      MappedCounterpartyMetadata.setLocation(metadataPrimaryKey, fr"physicallocation",
        physicalLocationId, userId, datePosted, longitude, latitude)

  // Deletes the where-tag row and leaves the pointer to it behind, exactly as Mapper's
  // `location.obj.map(_.delete_!)` did. A dangling pointer reads back as no location, so the
  // observable result is the same and no second write is needed.
  override val deleteCorporateLocation: () => Boolean =
    () => corporateLocationId.exists(MappedCounterpartyWhereTag.deleteById)
  override val deletePhysicalLocation: () => Boolean =
    () => physicalLocationId.exists(MappedCounterpartyWhereTag.deleteById)
}

object MappedCounterpartyMetadata {

  private val selectColumns =
    fr"""SELECT id, counterpartyid, counterpartyname, thisbankid, thisaccountid, publicalias,
                privatealias, moreinfo, url, imageurl, opencorporatesurl, corporatelocation,
                physicallocation
         FROM mappedcounterpartymetadata"""

  private type Row = (Long, Option[String], Option[String], Option[String], Option[String],
    Option[String], Option[String], Option[String], Option[String], Option[String], Option[String],
    Option[Long], Option[Long])

  private def fromRow(row: Row): MappedCounterpartyMetadata = row match {
    case (id, counterpartyId, counterpartyName, thisBankId, thisAccountId, publicAlias,
          privateAlias, moreInfo, url, imageUrl, openCorporatesUrl, corporateLocation,
          physicalLocation) =>
      MappedCounterpartyMetadata(id, counterpartyId.orNull, counterpartyName.orNull,
        thisBankId.orNull, thisAccountId.orNull, publicAlias.orNull, privateAlias.orNull,
        moreInfo.orNull, url.orNull, imageUrl.orNull, openCorporatesUrl.orNull,
        corporateLocation, physicalLocation)
  }

  private def query(condition: Fragment): List[MappedCounterpartyMetadata] =
    DoobieUtil.runQuery((selectColumns ++ condition).query[Row].to[List]).map(fromRow)

  private def opt(value: String): Option[String] = Option(value)

  private def one(condition: Fragment): Box[MappedCounterpartyMetadata] =
    query(condition ++ fr"ORDER BY id ASC LIMIT 1").headOption match {
      case Some(row) => Full(row)
      case None => Empty
    }

  def findByCounterpartyId(counterpartyId: String): Box[MappedCounterpartyMetadata] =
    one(fr"WHERE counterpartyid = ${opt(counterpartyId)}")

  def findAllByBankAndAccount(thisBankId: String, thisAccountId: String): List[MappedCounterpartyMetadata] =
    query(fr"WHERE thisbankid = ${opt(thisBankId)} AND thisaccountid = ${opt(thisAccountId)}")

  def findByBankAccountAndCounterpartyId(thisBankId: String, thisAccountId: String,
                                         counterpartyId: String): Box[MappedCounterpartyMetadata] =
    one(fr"""WHERE thisbankid = ${opt(thisBankId)} AND thisaccountid = ${opt(thisAccountId)}
               AND counterpartyid = ${opt(counterpartyId)}""")

  def countByCounterpartyId(counterpartyId: String): Long =
    DoobieUtil.runQuery(
      (fr"SELECT COUNT(*) FROM mappedcounterpartymetadata WHERE counterpartyid = ${opt(counterpartyId)}")
        .query[Long].unique)

  def insert(counterpartyId: String, thisBankId: String, thisAccountId: String,
             counterpartyName: String, publicAlias: String): MappedCounterpartyMetadata = {
    val now = new java.sql.Timestamp(System.currentTimeMillis())
    val id = DoobieUtil.runUpdate(
      sql"""INSERT INTO mappedcounterpartymetadata
            (counterpartyid, thisbankid, thisaccountid, counterpartyname, publicalias,
             privatealias, moreinfo, url, imageurl, opencorporatesurl, createdat, updatedat)
            VALUES (${opt(counterpartyId)}, ${opt(thisBankId)}, ${opt(thisAccountId)},
             ${opt(counterpartyName)}, ${opt(publicAlias)}, '', '', '', '', '', $now, $now)"""
        .update.withUniqueGeneratedKeys[Long]("id"))
    MappedCounterpartyMetadata(id, counterpartyId, counterpartyName, thisBankId, thisAccountId,
      publicAlias, "", "", "", "", "", None, None)
  }

  /** The metadata row an account gets before any counterparty is known: no id, no alias. */
  def insertForAccount(thisBankId: String, thisAccountId: String): MappedCounterpartyMetadata =
    insert(counterpartyId = "", thisBankId = thisBankId, thisAccountId = thisAccountId,
      counterpartyName = "", publicAlias = "")

  private[counterparties] def setText(metadataPrimaryKey: Long, column: Fragment,
                                      value: String): Boolean =
    tryo {
      DoobieUtil.runUpdate(
        (fr"UPDATE mappedcounterpartymetadata SET" ++ column ++ fr" = ${opt(value)}," ++
          fr"updatedat = ${new java.sql.Timestamp(System.currentTimeMillis())}" ++
          fr"WHERE id = $metadataPrimaryKey").update.run)
      true
    }.getOrElse(false)

  /**
   * Moves a map pin: updates the where-tag the metadata already points at, or creates one and
   * points at it. Mapper reused the existing row the same way, so a location that several readers
   * hold is updated in place rather than replaced.
   */
  private[counterparties] def setLocation(metadataPrimaryKey: Long, column: Fragment,
                                          existingTagId: Option[Long], userId: UserPrimaryKey,
                                          datePosted: Date, longitude: Double,
                                          latitude: Double): Boolean =
    tryo {
      val tagId = existingTagId match {
        case Some(id) =>
          MappedCounterpartyWhereTag.update(id, userId.value, datePosted, longitude, latitude)
          id
        case None =>
          MappedCounterpartyWhereTag.insert(userId.value, datePosted, longitude, latitude)
      }
      DoobieUtil.runUpdate(
        (fr"UPDATE mappedcounterpartymetadata SET" ++ column ++ fr" = $tagId," ++
          fr"updatedat = ${new java.sql.Timestamp(System.currentTimeMillis())}" ++
          fr"WHERE id = $metadataPrimaryKey").update.run)
      true
    }.getOrElse(false)

  def deleteById(metadataPrimaryKey: Long): Boolean =
    DoobieUtil.runUpdate(
      sql"DELETE FROM mappedcounterpartymetadata WHERE id = $metadataPrimaryKey".update.run) > 0

  def deleteAll(): Unit = {
    DoobieUtil.runUpdate(sql"DELETE FROM mappedcounterpartymetadata".update.run)
    ()
  }
}

/** One map pin: where a counterparty is, according to the user who posted it. */
case class MappedCounterpartyWhereTag(
  whereTagPrimaryKey: Long,
  userPrimaryKey: Long,
  date: Date,
  geoLatitude: Double,
  geoLongitude: Double
) extends GeoTag {
  override def postedBy: Box[User] = Users.users.vend.getUserByResourceUserId(userPrimaryKey)
  override def datePosted: Date = date
  override def latitude: Double = geoLatitude
  override def longitude: Double = geoLongitude
}

object MappedCounterpartyWhereTag {

  // user and date carry the Schemifier suffix for reserved words.
  private val selectColumns =
    fr"SELECT id, user_c, date_c, geolatitude, geolongitude FROM mappedcounterpartywheretag"

  private type Row = (Long, Option[Long], Option[java.sql.Timestamp], Option[Double], Option[Double])

  private def fromRow(row: Row): MappedCounterpartyWhereTag = row match {
    case (id, userPrimaryKey, date, geoLatitude, geoLongitude) =>
      MappedCounterpartyWhereTag(id, userPrimaryKey.getOrElse(0L),
        date.map(ts => ts: Date).orNull, geoLatitude.getOrElse(0d), geoLongitude.getOrElse(0d))
  }

  def findById(whereTagPrimaryKey: Long): Option[MappedCounterpartyWhereTag] =
    DoobieUtil.runQuery(
      (selectColumns ++ fr"WHERE id = $whereTagPrimaryKey").query[Row].to[List])
      .map(fromRow).headOption

  def insert(userPrimaryKey: Long, datePosted: Date, longitude: Double, latitude: Double): Long = {
    val now = new java.sql.Timestamp(System.currentTimeMillis())
    DoobieUtil.runUpdate(
      sql"""INSERT INTO mappedcounterpartywheretag
            (user_c, date_c, geolatitude, geolongitude, createdat, updatedat)
            VALUES ($userPrimaryKey, ${Option(datePosted).map(d => new java.sql.Timestamp(d.getTime))},
             $latitude, $longitude, $now, $now)"""
        .update.withUniqueGeneratedKeys[Long]("id"))
  }

  def update(whereTagPrimaryKey: Long, userPrimaryKey: Long, datePosted: Date, longitude: Double,
             latitude: Double): Unit = {
    val now = new java.sql.Timestamp(System.currentTimeMillis())
    DoobieUtil.runUpdate(
      sql"""UPDATE mappedcounterpartywheretag
            SET user_c = $userPrimaryKey,
                date_c = ${Option(datePosted).map(d => new java.sql.Timestamp(d.getTime))},
                geolatitude = $latitude, geolongitude = $longitude, updatedat = $now
            WHERE id = $whereTagPrimaryKey"""
        .update.run)
    ()
  }

  def deleteById(whereTagPrimaryKey: Long): Boolean =
    DoobieUtil.runUpdate(
      sql"DELETE FROM mappedcounterpartywheretag WHERE id = $whereTagPrimaryKey".update.run) > 0

  def deleteAll(): Unit = {
    DoobieUtil.runUpdate(sql"DELETE FROM mappedcounterpartywheretag".update.run)
    ()
  }
}

/**
 * An explicit counterparty: one the account holder created through the API, as opposed to the
 * implicit ones derived from transactions, which are never stored here.
 *
 * `counterpartyPrimaryKey` is the surrogate key and would normally stay inside the store, but the
 * bespoke key/value rows are keyed by it rather than by the counterparty id, so it has to be
 * carried on the row for `bespoke` to resolve.
 */
case class MappedCounterparty(
  counterpartyPrimaryKey: Long,
  counterpartyId: String,
  name: String,
  createdByUserId: String,
  thisBankId: String,
  thisAccountId: String,
  thisViewId: String,
  otherBankRoutingScheme: String,
  otherBankRoutingAddress: String,
  otherBranchRoutingScheme: String,
  otherBranchRoutingAddress: String,
  otherAccountRoutingScheme: String,
  otherAccountRoutingAddress: String,
  otherAccountSecondaryRoutingScheme: String,
  otherAccountSecondaryRoutingAddress: String,
  isBeneficiary: Boolean,
  description: String,
  currency: String
) extends CounterpartyTrait {

  override def bespoke: List[CounterpartyBespoke] =
    CounterpartyBespokes.counterpartyBespokers.vend
      .getCounterpartyBespokesByCounterpartyId(counterpartyPrimaryKey)
      .map(
        mappedBespoke=>CounterpartyBespoke(mappedBespoke.key,mappedBespoke.value)
      )
}

